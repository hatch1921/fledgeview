from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
    pg = b.new_page(viewport={'width': 1920, 'height': 1080}, color_scheme='dark'); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.route('**/exifr@7.1.3/dist/full.umd.js', lambda r: r.fulfill(path='/tmp/libs/exifr-7.1.3/dist/full.umd.js', content_type='application/javascript'))
    pg.route('**/jszip.min.js', lambda r: r.fulfill(path='/tmp/libs/jszip-3.10.1/dist/jszip.min.js', content_type='application/javascript'))
    pg.route('https://fonts.**', lambda r: r.abort())
    pg.goto('file:///tmp/fv_reach_test.html'); pg.wait_for_timeout(800)
    pg.evaluate("document.getElementById('guideDlg').close()")
    pg.set_input_files('#fileInput', ['/mnt/user-data/uploads/A1200001.ARW', '/tmp/vid/Wildlife/2026-09-04/A1208483.jpg']); pg.wait_for_timeout(3000)
    pg.click('#strip [aria-label="A1200001.ARW"]'); pg.wait_for_timeout(2500)
    pg.click('#cropTab'); pg.wait_for_timeout(1000)
    info = lambda: pg.evaluate("document.getElementById('eCropInfo').textContent")
    print('full frame:', info())
    print('reach buttons:', pg.evaluate("[document.getElementById('eReach14').textContent, document.getElementById('eReach2').textContent]"))
    pg.click('#eReach14'); pg.wait_for_timeout(400); print('+1.4x ->', info())
    pg.click('#eReach2'); pg.wait_for_timeout(400); print('+2x   ->', info())
    pg.fill('#eReachMm', '1000'); pg.press('#eReachMm', 'Enter'); pg.wait_for_timeout(400); print('1000 mm typed ->', info())
    pg.fill('#eReachMm', '400'); pg.press('#eReachMm', 'Enter'); pg.wait_for_timeout(400); print('400 mm (shorter than the photo) ->', pg.evaluate("document.getElementById('toast').textContent"))
    pg.click('#eCropReset'); pg.wait_for_timeout(300); pg.check('#eReachGuides'); pg.wait_for_timeout(500)
    pg.screenshot(path='/tmp/reach_guides.png')
    hits = pg.evaluate("window.__hits()"); print('guides drawn:', [round(h['T']) for h in hits])
    h2 = [h for h in hits if round(h['T']) == 1200][0]; pg.mouse.click(h2['x'], h2['y']); pg.wait_for_timeout(500); print('clicked the 2x guide ->', info())
    pg.click('#eCropBtn'); pg.wait_for_timeout(500)
    print('saved crop:', pg.evaluate("(() => { const e = JSON.parse(localStorage.getItem('chimp-edits') || '{}'); const r = Object.values(e)[0]; return r && r.crop ? 'yes' : 'no'; })()"))
    print('info bar text:', pg.evaluate("window.__bar('A1200001.ARW')"))
    print('uncropped photo bar text:', pg.evaluate("window.__bar('A1208483.jpg')"))
    print('Crop reach field listed:', pg.evaluate("(() => { document.getElementById('webBtn').click(); return [...document.querySelectorAll('#wFields label')].map(l => l.textContent.trim()); })()"))
    print('errors:', errs)
    b.close()
